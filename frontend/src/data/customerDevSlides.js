/* Булиты: с заглавной + «;», последний — «.». Вопросы/восклицания сохраняются. */
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const stripEnd = (s) => s.replace(/[.;]+\s*$/, "").trim();
export const fmtList = (items) =>
  items.map((it, i) => {
    const t = it.trim();
    const last = t.slice(-1);
    if (last === "?" || last === "!") return cap(t);
    return cap(stripEnd(t)) + (i === items.length - 1 ? "." : ";");
  });

/* Нумерованные шаги: с заглавной + «.». */
export const fmtSteps = (items) => items.map((it) => cap(stripEnd(it.trim())) + ".");

/* Плотные слайды используют меньший (второй) размер основного текста.
   Можно переопределить флагом `dense` на самом слайде. */
export const isDense = (s) => {
  if (typeof s.dense === "boolean") return s.dense;
  return (s.blocks || []).some((b) =>
    (b.k === "bul" && ((b.items && b.items.length >= 8) || b.cols === 3)) ||
    (b.k === "steps" && b.items && b.items.length >= 9) ||
    (b.k === "cards" && b.items && b.items.length >= 5)
  );
};

